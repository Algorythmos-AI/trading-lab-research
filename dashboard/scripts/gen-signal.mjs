// Generates src/lib/signal-version.gen.ts: the Options desk signal's code hash (DEC-0051 sections 1 and 8), from the
// code itself, the way scripts/gen-engine.mjs labels the engine.
//
// It walks the import closure of src/lib/signal.ts within src/lib (relative "./x" and "@/lib/x" imports, .ts and
// .json; the walk is gen-engine.mjs's, copied here because gen-engine's is fixed to desk-eval.ts), so a change to
// flow.ts, context.ts, option-value.ts, board-events.ts or any other rule the signal imports moves the hash. Every file
// is hashed in path order with comments and spacing dropped (gen-engine.mjs's tokens(): TypeScript's own scanner, so a
// string keeps its spaces), and SIGNAL_CODE_HASH = "s-<sha-256 hex>" is written. Left out: signal-freeze.ts (it holds
// the frozen hashes: including it would be circular), this generated file, and engine-version.gen.ts.
//
//   node scripts/gen-signal.mjs          write the file
//   node scripts/gen-signal.mjs --check  exit 1 when the file on disk is stale (the unit test runs this)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { tokens } from "./gen-engine.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = join(root, "src/lib");
const OUT = join(lib, "signal-version.gen.ts");

const ENTRY = join(lib, "signal.ts");
/** Never in the hash: the frozen hashes, the generated hash itself, and the engine's generated label. */
export const EXCLUDED = ["signal-freeze.ts", "signal-version.gen.ts", "engine-version.gen.ts"].map((f) => join(lib, f));

function resolve(from, spec) {
  let base;
  if (spec.startsWith("@/lib/")) base = join(lib, spec.slice("@/lib/".length));
  else if (spec.startsWith("./") || spec.startsWith("../")) base = join(dirname(from), spec);
  else return null;
  for (const f of [base, `${base}.ts`, `${base}/index.ts`]) if (f.startsWith(lib) && /\.(ts|json)$/.test(f) && existsSync(f)) return f;
  return null;
}

/** The import closure of signal.ts within src/lib, the excluded files left out, sorted. */
export function signalFiles() {
  const seen = new Set();
  const todo = [ENTRY];
  while (todo.length) {
    const f = todo.pop();
    if (seen.has(f) || EXCLUDED.includes(f)) continue;
    seen.add(f);
    if (f.endsWith(".json")) continue;
    const src = ts.createSourceFile(f, readFileSync(f, "utf8"), ts.ScriptTarget.Latest, false);
    const specs = [];
    const visit = (n) => {
      if ((ts.isImportDeclaration(n) || ts.isExportDeclaration(n)) && n.moduleSpecifier && ts.isStringLiteral(n.moduleSpecifier)) specs.push(n.moduleSpecifier.text);
      if (ts.isCallExpression(n) && n.expression.kind === ts.SyntaxKind.ImportKeyword && n.arguments[0] && ts.isStringLiteral(n.arguments[0])) specs.push(n.arguments[0].text);
      ts.forEachChild(n, visit);
    };
    visit(src);
    for (const sp of specs) {
      const r = resolve(f, sp);
      if (r && !EXCLUDED.includes(r)) todo.push(r);
    }
  }
  return [...seen].sort();
}

export function signalHash() {
  const h = createHash("sha256");
  for (const f of signalFiles()) {
    const text = readFileSync(f, "utf8");
    h.update(`${relative(lib, f)}\n`);
    h.update(f.endsWith(".json") ? JSON.stringify(JSON.parse(text)) : tokens(text));
    h.update("\n");
  }
  return `s-${h.digest("hex")}`;
}

export function render(hash) {
  return `// Generated by \`node scripts/gen-signal.mjs\` from the signal's code and its import closure. Do not edit by hand.\nexport const SIGNAL_CODE_HASH = "${hash}";\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = render(signalHash());
  if (process.argv.includes("--check")) {
    const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (have !== want) {
      console.error("src/lib/signal-version.gen.ts is stale: run node scripts/gen-signal.mjs");
      process.exit(1);
    }
  } else writeFileSync(OUT, want);
}
