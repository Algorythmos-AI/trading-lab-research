// Generates src/lib/engine-version.gen.ts: the desk engine's label (DEC-0044), from the code itself.
//
// It walks the import closure of src/lib/desk-eval.ts within src/lib (relative "./x" and "@/lib/x" imports, .ts and
// .json), drops every comment and all spacing between tokens (TypeScript's own scanner, so a string keeps its
// spaces), hashes the files in path order, and writes ENGINE_VERSION = "e-<first 12 hex>". A change to any line of
// code the server's evaluation runs gives a new label; a comment or a reflow does not.
//
//   pnpm gen:engine          write the file
//   pnpm gen:engine --check  exit 1 when the file on disk is stale (the unit test runs this)
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = join(root, "src/lib");
const ENTRY = join(lib, "desk-eval.ts");
const OUT = join(lib, "engine-version.gen.ts");

function resolve(from, spec) {
  let base;
  if (spec.startsWith("@/lib/")) base = join(lib, spec.slice("@/lib/".length));
  else if (spec.startsWith("./") || spec.startsWith("../")) base = join(dirname(from), spec);
  else return null;
  for (const f of [base, `${base}.ts`, `${base}/index.ts`]) if (f.startsWith(lib) && /\.(ts|json)$/.test(f) && existsSync(f)) return f;
  return null;
}

/** The file's tokens, comments and spacing dropped, joined by one space. */
export function tokens(text) {
  const sc = ts.createScanner(ts.ScriptTarget.Latest, true, ts.LanguageVariant.Standard, text);
  const out = [];
  for (let k = sc.scan(); k !== ts.SyntaxKind.EndOfFileToken; k = sc.scan()) out.push(sc.getTokenText());
  return out.join(" ");
}

export function engineFiles() {
  const seen = new Set();
  const todo = [ENTRY];
  while (todo.length) {
    const f = todo.pop();
    if (seen.has(f) || f === OUT) continue;
    seen.add(f);
    if (f.endsWith(".json")) continue;
    const src = ts.createSourceFile(f, readFileSync(f, "utf8"), ts.ScriptTarget.Latest, false);
    const specs = [];
    const visit = (n) => {
      if ((ts.isImportDeclaration(n) || ts.isExportDeclaration(n)) && n.moduleSpecifier && ts.isStringLiteral(n.moduleSpecifier)) specs.push(n.moduleSpecifier.text);
      if (ts.isCallExpression(n) && n.expression.kind === ts.SyntaxKind.ImportKeyword && n.arguments[0] && ts.isStringLiteral(n.arguments[0])) specs.push(n.arguments[0].text);
      ts.forEachChild(n, visit);
    };
    visit(src);
    for (const s of specs) {
      const r = resolve(f, s);
      if (r && r !== OUT) todo.push(r);
    }
  }
  return [...seen].sort();
}

export function engineVersion() {
  const h = createHash("sha256");
  for (const f of engineFiles()) {
    const text = readFileSync(f, "utf8");
    h.update(`${relative(lib, f)}\n`);
    h.update(f.endsWith(".json") ? JSON.stringify(JSON.parse(text)) : tokens(text));
    h.update("\n");
  }
  return `e-${h.digest("hex").slice(0, 12)}`;
}

export function render(version) {
  return `// Generated by \`pnpm gen:engine\` (scripts/gen-engine.mjs) from the desk engine's code. Do not edit by hand.\nexport const ENGINE_VERSION = "${version}";\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = render(engineVersion());
  if (process.argv.includes("--check")) {
    const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (have !== want) {
      console.error("src/lib/engine-version.gen.ts is stale: run pnpm gen:engine");
      process.exit(1);
    }
  } else writeFileSync(OUT, want);
}
